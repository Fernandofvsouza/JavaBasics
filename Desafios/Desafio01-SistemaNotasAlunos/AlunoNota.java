public class AlunoNota {
    private String nome;
    private double notaMatematica;
    private double notaPortugues;
    private double notaCiencias;
    private double notaFisica;



    public String getNome() {
        return nome;
    }

    public double getNotaMatematica() {
        return notaMatematica;
    }

    public double getNotaPortugues() {
        return notaPortugues;
    }

    public double getNotaCiencias() {
        return notaCiencias;
    }

    public double getNotaFisica() {
        return notaFisica;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public void setNotaMatematica(double notaMatematica) {
        this.notaMatematica = notaMatematica;
    }

    public void setNotaPortugues(double notaPortugues) {
        this.notaPortugues = notaPortugues;
    }

    public void setNotaCiencias(double notaCiencias) {
        this.notaCiencias = notaCiencias;
    }

    public void setNotaFisica(double notaFisica) {
        this.notaFisica = notaFisica;
    }
}
