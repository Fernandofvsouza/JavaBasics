/*
* Operadores aritmeticos sao usados para realizar operações matemáticas em variáveis e valores.
* Os operadores aritmeticos incluem:
* - Adição (+): Soma dois operandos. Exemplo: a + b
* - Subtração (-): Subtrai o segundo operando do primeiro. Exemplo
* - Multiplicação (*): Multiplica dois operandos. Exemplo: a * b
* - Divisão (/): Divide o primeiro operando pelo segundo. Exemplo: a /
* - Módulo (%): Retorna o resto da divisão do primeiro operando pelo segundo. Exemplo: a % b
*
* Precedencia dos operadores aritmeticos:
* 1. Parenteses ()
* 2. Multiplicação (*) e Divisão (/)
* 3. Adição (+) e Subtração (-)
*
*
*
* */



public class OperadoresAritmeticos {
    static void main(String[] args) {
        int numero1 = 10;
        int numero2 = 5;
        int soma = numero1 + numero2; // Adição
        int subtracao = numero1 - numero2; // Subtração
        int multiplicacao = numero1 * numero2; // Multiplicação
        int divisao = numero1 / numero2; // Divisão
        int modulo = numero1 % numero2; // Módulo
    }
}
