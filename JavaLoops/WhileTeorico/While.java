/*
*Como argumento o while so aceita um valoor booleano
* O loop será executado até que o valor em parenteses seja falso
*
*
* */


public class While {
    static void main() {
        int n1 = 5;
        int n2 = 0;
        while (n1 > n2){
            System.out.println("Teste: " + n2);
            n2++;
        }
    }
}
