/*
* Fluxos Excepcionais
* Exceção é um fluxo inesperado na aplicação e um erro é a interrupçao do seu sistema
* Isso significa que uma exceção poderá ser tratada atraves de um desvio de fluxo,
* enquanto um erro ocasiona na reinicialização do programa
*
* Uma das habilidades cruciais de um programador é a previsibilidade de possiveis exceções
* Exemplos:
* Tentar usar algum metodo em uma variavel sem referencia (NullPointerException)
* Tentar ler um arquivo que não existe (FileNotFoundException)
* Tentar transformar um texto em numero (NumberFormatException)
* Tentar pegar um elemento que nao existe no array (ArrayIndexOutOfBoundsException)
*
*Para o tratamento de exceções é necessario ter o dominio
* do try e catch, onde o try é a parte do codigo onde pode ocorrer a exceção e o catch é a parte onde o tratamento da exceção acontece
* e o finally é a parte onde o codigo é executado independente de ter ocorrido ou nao a exceção
*
* RunTimeException é uma exceção que não precisa ser tratada, ou seja, não precisa usar o try catch ou lançar a exceção para o metodo que chamou, usando o throws
* Exception é uma exceção que precisa ser tratada, ou seja, precisa usar o try catch ou lançar a exceção para o metodo que chamou, usando o throws
* */



